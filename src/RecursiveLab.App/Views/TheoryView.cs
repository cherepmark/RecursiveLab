РЕКУРСИЯ: ОСНОВНЫЕ ИДЕИ

Рекурсивная функция — функция, которая вызывает саму себя на задаче меньшего размера.
Любая корректная рекурсия состоит из двух обязательных частей:

1) БАЗОВЫЙ СЛУЧАЙ — условие, при котором рекурсивный вызов не выполняется.
   Именно он останавливает рекурсию. Если базовый случай отсутствует или никогда
   не достигается, происходит переполнение стека вызовов.
2) РЕКУРСИВНЫЙ ШАГ — сведение задачи к задаче меньшего размера плюс несколько
   действий, которые нужно выполнить самому.

Изменение глубины рекурсии — это изменение количества уровней дробления задачи.
Чем больше уровней, тем выше детализация результата и тем больше работы выполняется.


1. ТРЕУГОЛЬНИК СЕРПИНСКОГО

Шаг рекурсии: треугольник делится средними линиями на четыре равных треугольника,
центральный (перевёрнутый) отбрасывается, а три угловых обрабатываются рекурсивно
с глубиной на единицу меньше.

Базовый случай: глубина равна 0 — треугольник добавляется в результат целиком.

Количество треугольников: 3^depth. Прирост площади: на каждом уровне остаётся
3/4 площади предыдущего уровня, то есть периметр растёт, а площадь стремится к нулю.
Ограничение глубины в программе: 10 (59049 треугольников) — дальше отдельные
треугольники становятся меньше пикселя.


2. СНЕЖИНКА КОХА

Шаг рекурсии: сторона делится на три равные части; на средней трети строится
«горб» — равносторонний треугольник, направленный наружу. Одна сторона
превращается в четыре отрезка, каждый из которых обрабатывается рекурсивно.

Базовый случай: глубина равна 0 — сторона остаётся одним отрезком.

Количество отрезков: 3 · 4^depth; каждое звено короче предыдущего в 3 раза,
а суммарная длина растёт как (4/3)^depth — классический пример фрактальной кривой
с бесконечной длиной при ограниченной площади.
Ограничение глубины: 7 (49152 отрезка).


3. ФРАКТАЛЬНОЕ ДЕРЕВО

Шаг рекурсии: из конца ветви выпускаются две ветви под углом ±26° к ней,
каждая короче предыдущей в 0,72 раза.

Базовый случай: глубина равна 0 — ветвь рисуется и больше не делится.

Количество ветвей: 2^(depth + 1) − 1. Наклон ветви ограничен ±75° от вертикали,
чтобы крона не «заваливалась» вниз.
Ограничение глубины: 14 (32767 отрезков).


4. КРИВАЯ ГИЛЬБЕРТА

Рекурсия с двумя параметрами: порядком (глубиной) и ориентацией подкривой.
Квадрат делится на четыре подквадрата, каждый обходится такой же кривой на единицу
меньшего порядка, а положение и поворот каждой копии задаёт ориентация.

Ориентация — одна из четырёх симметрий квадрата: тождественное преобразование,
отражение по главной диагонали, отражение по побочной диагонали и поворот на 180°.
Все четыре являются инволюциями, а их композиция совпадает с побитовым сложением,
поэтому ориентация подкривой вычисляется как «ориентация родителя XOR код подквадрата».

Базовый случай: порядок 1 — заготовка из четырёх точек, начинающаяся в левом верхнем
углу квадрата и заканчивающаяся в правом верхнем. Именно такое расположение начала и
конца делает базовый случай согласованным с рекурсией на всех порядках.

Число отрезков: 4^depth − 1. Кривая заполняет квадрат 2^depth × 2^depth, проходя каждую
клетку ровно один раз и нигде себя не пересекая. Встроенная проверка сравнивает
последовательность точек с классическим алгоритмом «индекс → точка» (d2xy).
Ограничение глубины: 7 (16383 отрезка).


ХАНОЙСКАЯ БАШНЯ: РЕКУРСИВНЫЙ АЛГОРИТМ

Задача: перенести n дисков со стержня A на стержень C, используя стержень B,
перекладывая по одному диску и не кладя больший диск на меньший.

Алгоритм переноса башни из n дисков с from на to через via:
1) перенести n − 1 диск с from на via;
2) перенести n-й (самый большой) диск с from на to;
3) перенести n − 1 диск с via на to.

Базовый случай: n = 1 — один диск переносится напрямую одним ходом.

Почему это работает: после шага 1 все диски, кроме самого большого, находятся на
вспомогательном стержне, поэтому большой диск свободно переносится на цель.
Количество ходов T(n) удовлетворяет равенству T(n) = 2·T(n − 1) + 1, T(1) = 1,
откуда T(n) = 2^n − 1. Это доказывает оптимальность решения.

Глубина рекурсии равна количеству дисков: для 12 дисков это 12 вложенных вызовов.


ХАНОЙСКАЯ БАШНЯ: РЕШЕНИЕ ЧЕРЕЗ ЯВНЫЙ СТЕК

Системный стек вызовов — это просто структура данных, которой управляет среда
выполнения: при каждом вызове функции на него кладётся «кадр» с параметрами
и адресом возврата. Тот же самый кадр можно хранить в обычном стеке (Stack<T>)
и обрабатывать в цикле while — тогда рекурсивные вызовы не нужны.

Кадр стековой реализации: (n, from, to, via, expanded).
Алгоритм:
  Стек ← { (n, from, to, via, expanded = false) }
  Пока стек не пуст:
    кадр ← Снять со стека
    если n = 1 → выполнить перенос одного диска (базовый случай)
    иначе если expanded = false:
        положить в стек в ОБРАТНОМ порядке три задачи:
          (n − 1, via, to, from, false)          — третий шаг
          (n,    from, to, via, true)           — второй шаг (перенос большого диска)
          (n − 1, from, via, to, false)         — первый шаг
    иначе → выполнить перенос самого большого диска

Порядок извлечения кадров из стека (LIFO) воспроизводит порядок рекурсивных
вызовов, поэтому последовательность перемещений в точности совпадает с рекурсивной.
Это проверяется автоматическими тестами: для 1..12 дисков обе реализации дают
одинаковый список ходов из 2^n − 1 перемещений.

Дополнительное доказательство отсутствия рекурсии выполняется на уровне IL-кода:
тест проверяет, что метод Solve стекового решателя не содержит вызова самого себя,
а для рекурсивного решателя такой вызов, наоборот, обязан быть найден.


САМОСТОЯТЕЛЬНЫЕ АЛГОРИТМЫ (ИНДИВИДУАЛЬНОЕ ЗАДАНИЕ)

1. АЛГОРИТМ ФЛОЙДА — УОРШЕЛЛА: КРАТЧАЙШИЕ ПУТИ, ТРОИЧНАЯ РЕКУРСИЯ

Задача: найти кратчайшие расстояния между всеми парами вершин взвешенного графа.
Ключевая идея: путь из i в j либо не проходит через вершину k, либо проходит через неё:

    D(k, i, j) = min( D(k−1, i, j), D(k−1, i, k−1) + D(k−1, k−1, j) )

где k — количество разрешённых промежуточных вершин. Базовый случай k = 0: расстояния
равны прямым рёбрам графа (если ребра нет, расстояние равно бесконечности).

Каждый вызов порождает ТРИ вызова предыдущего уровня, поэтому на одну пару вершин
приходится 3^k вызовов, а на весь граф — n²·3^n. Число вызовов удовлетворяет равенству
T(k) = 1 + 3·T(k−1), T(0) = 1, то есть T(k) = (3^(k+1) − 1) / 2.

В программе реализованы три версии одного и того же правила:
  * рекурсия без мемоизации — 3^k вызовов на пару, наглядный пример экспоненциальности;
  * рекурсия с мемоизацией — значение D(k,i,j) вычисляется один раз и запоминается,
    число вычислений становится равным числу состояний (n+1)·n², сложность O(n³);
  * классические три цикла — эталон; дополнительно строится матрица «следующая вершина»,
    по которой восстанавливаются сами пути, а не только расстояния.

На демонстрационном графе из шести вершин: без мемоизации — 39 348 вызовов,
с мемоизацией — 684, итеративно — 0. Матрицы расстояний у всех трёх версий совпадают,
а для каждого восстановленного пути сумма весов рёбер равна расстоянию в матрице.


2. КРИВАЯ ГИЛЬБЕРТА: ФРАКТАЛЬНАЯ РЕКУРСИЯ С ПАРАМЕТРАМИ ГЛУБИНЫ И ОРИЕНТАЦИИ

Кривая Гильберта — пространственная кривая, которая заполняет квадрат 2^n × 2^n,
проходя каждую клетку ровно один раз и нигде себя не пересекая. Рекурсия: квадрат делится
на четыре подквадрата, каждый обходится такой же кривой на единицу меньшего порядка.

Второй параметр рекурсии — ориентация подкривой (одна из четырёх симметрий квадрата:
тождественное преобразование, отражение по главной диагонали, отражение по побочной
диагонали, поворот на 180°). Все четыре — инволюции, а их композиция совпадает с
побитовым сложением, поэтому ориентация подкривой равна «ориентация родителя XOR
код подквадрата». Базовый случай — порядок 1: заготовка из четырёх точек.

Число отрезков: 4^depth − 1. Корректность проверяется сравнением с классическим
алгоритмом «индекс → точка» (d2xy) — последовательности точек полностью совпадают,
что видно прямо на странице алгоритма.


3. АЛГОРИТМ ШТРАССЕНА: УМНОЖЕНИЕ МАТРИЦ ПО ПРИНЦИПУ «РАЗДЕЛЯЙ И ВЛАСТВУЙ»

Обычное блочное умножение матриц размера n = 2^k требует 8 рекурсивных умножений
половинного размера. Штрассен обходится семью промежуточными произведениями:

    M1 = (A11+A22)(B11+B22)        M5 = (A11+A12)·B22
    M2 = (A21+A22)·B11             M6 = (A21−A11)(B11+B12)
    M3 = A11·(B12−B22)             M7 = (A12−A22)(B21+B22)
    M4 = A22·(B21−B11)

    C11 = M1+M4−M5+M7     C12 = M3+M5
    C21 = M2+M4           C22 = M1−M2+M3+M6

Отсюда T(n) = 7·T(n/2) + O(n²), то есть сложность O(n^log2 7) ≈ O(n^2.807) вместо O(n³).

Базовый случай рекурсии — блок размером не больше выбранного порога: такой блок
перемножается обычным тройным циклом. Матрицы дополняются нулями до степени двойки,
поэтому поддерживаются и нечётные размеры (например, 17×17 дополняется до 32×32).

Показательные числа из самопроверки: для размера 8 при пороге 1 выполняется
7³ = 343 скалярных умножения вместо 8³ = 512; для размера 32 — 19 208 вместо 32 768
(при пороге 2). Результат совпадает с классическим алгоритмом, а матрица разности нулевая.


